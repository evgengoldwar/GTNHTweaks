package gtnhtweaks.modules.bees.client;

/** What the body of a bee is like, besides its colors. */
enum Skin {

    NORMAL,
    /** Shiny, with highlights along its edges: the metal bees. */
    METAL,
    /** Glows by itself, not darker at night: the radioactive and fire bees. */
    GLOW,
    /** See-through: the ghostly bees. */
    GHOST,
    /** A core in a see-through shell, like a slime: the slimy and sticky bees. */
    SLIME,
    /** With glinting facets: the gem bees. */
    CRYSTAL,
    /** Speckled like stone: the stone and earth bees. */
    STONE,
    /** Pale, stitched and bandaged: the undead bees. */
    UNDEAD,
    /** Dark as space, with twinkling stars: the bees of the end of the game. */
    COSMIC
}
